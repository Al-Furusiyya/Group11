"""Run actual CPU/JTAG/PS2/VGA RTL and Python host tests. Icarus on PATH."""
from pathlib import Path
import subprocess,sys,shutil
from fixtures import fixtures
ROOT=Path(__file__).resolve().parents[1]
def run(args,**kwargs):return subprocess.run(args,cwd=ROOT,check=True,**kwargs)
def hdl():
    names=['demo_VGA_Python.v','vga_scene.v','vga_timing.v','sprite_smoother.v','PS2Keyboard.v','PS2Receiver.v','PS2KeyDecoder.v','KeyboardCommands.v']
    return [*(ROOT/n for n in names),*sorted((ROOT/'CPU').glob('*.v')),*sorted((ROOT/'JTAG').glob('*.v')),ROOT/'sim/sld_virtual_jtag_model.v']
if __name__=='__main__':
    (ROOT/'sim/rtl_verified.marker').unlink(missing_ok=True)
    if not shutil.which('iverilog') or not shutil.which('vvp'):
        raise SystemExit('RTL checks require Icarus Verilog (iverilog and vvp) on PATH. Software tests: python -m unittest discover -s sim -p "test_*.py" -v')
    run([sys.executable,'CPU/build_firmware.py'])
    fixtures()
    sources=hdl()
    for standard in ['-g2005','-g2012']:
        run(['iverilog',standard,'-Wall','-Wno-timescale','-s','demo_VGA_Python','-o','sim/top.vvp',*map(str,sources)])
    run(['iverilog','-g2005','-Wall','-Wno-timescale','-s','tb_jtag_transport','-o','sim/transport.vvp',str(ROOT/'JTAG/jtag_display_link.v'),'sim/tb_jtag_transport.v'])
    transport=run(['vvp','sim/transport.vvp'],capture_output=True,text=True)
    print(transport.stdout,end='')
    assert 'PASS: transport' in transport.stdout and 'FAIL:' not in transport.stdout,transport.stdout
    run(['iverilog','-g2005','-Wall','-Wno-timescale','-s','tb_system','-o','sim/system.vvp',*map(str,sources),'sim/tb_system.v'])
    result=run(['vvp','sim/system.vvp'],capture_output=True,text=True)
    print(result.stdout,end='')
    assert 'PASS: JTAG scans' in result.stdout and 'FAIL:' not in result.stdout,result.stdout
    (ROOT/'sim/rtl_verified.marker').write_text('Generated by successful current RTL run\n')
    run([sys.executable,'-m','unittest','discover','-s','sim','-p','test_*.py','-v'])

    for top in ['tb_sprite_smoother','tb_vga_output','tb_scene_checks']:
        executable=f'sim/{top}.vvp'
        run(['iverilog','-g2005','-Wno-timescale','-s',top,'-o',executable,*map(str,sources),f'sim/{top}.v'])
        result=run(['vvp',executable],capture_output=True,text=True)
        assert 'FAIL' not in result.stdout and 'PASS' in result.stdout,result.stdout
        print(result.stdout,end='')

    # Existing Lab4 tests still run with the added memory-mapped bus.
    for top in ['tb_CPU_Part1','tb_CPU_Branch','tb_CPUControl','tb_InstructionDecoder','tb_BranchCondition','tb_ProgramCounter','tb_PS2Keyboard']:
        executable=f'sim/{top}.vvp'
        run(['iverilog','-g2005','-Wno-timescale','-s',top,'-o',executable,*map(str,sources),f'sim/{top}.v'])
        result=run(['vvp',executable],capture_output=True,text=True)
        assert 'FAIL' not in result.stdout and 'PASS' in result.stdout,result.stdout
        print('PASS: uploaded regression '+top)
